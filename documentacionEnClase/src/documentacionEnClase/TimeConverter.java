package documentacionEnClase;

/**
 * Esta clase calcula diferentes tipos de formato de hora a otros
 */

public class TimeConverter {

	/**
	 * 
	 * Este metodo realiza la conversion de los minutos pasados a segundos
	 * 
	 * @param Cantidad de minutos a convertir a segundos
	 * @return los segundos despues de calcularlos
	 */

	public int minutosASegundos(int minutos) {
		return minutos * 60;
	}

}
